#!/usr/bin/env node
/* Inject the <head> metadata every page needs for search results and link
 * previews: description, canonical, Open Graph, Twitter card, favicon.
 *
 * Also normalises two things that had drifted apart across the 12 pages:
 *   - the Google Fonts URL (four pages asked for DM Mono 300;400 and eight for
 *     300;400;500, which is a cache miss on every navigation between the two
 *     groups, and a visible weight shift)
 *   - the preconnect hints (every page preconnected to fonts.googleapis.com,
 *     which serves only the stylesheet; the font files come from
 *     fonts.gstatic.com, which nobody preconnected to)
 *
 * Idempotent: safe to re-run. Run from anywhere: node tools/add-head-meta.js
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://katjanorstad.no';
const CANONICAL_MONO = 'DM+Mono:wght@300;400;500';

// slug -> { title for link previews, description for search results }
// Descriptions are written to read as a sentence in a search result, not as
// keyword soup, and are kept inside the ~155 chars Google renders.
const PAGES = {
  'index': {
    title: 'Katja Norstad',
    desc: 'Data scientist in Oslo. A pomodoro timer, daily language practice with spaced repetition, coffee tasting notes, and a few other things I built.'
  },
  'cv': {
    title: 'Curriculum Vitae — Katja Norstad',
    desc: 'Curriculum vitae of Katja Norstad, a data scientist based in Oslo working with data since 2012.'
  },
  'resources': {
    title: 'Worth your time',
    desc: 'A small collection of books, tools and links I keep coming back to, with a line on why each one earned its place.'
  },
  'pomodoro': {
    title: 'Pomodoro Timer',
    desc: 'A pomodoro timer shaped like an hourglass. Twenty-five minute focus sessions, short breaks, and a long break every fourth round.'
  },
  'languages': {
    title: 'Practise a language',
    desc: 'Practise French, Spanish, Portuguese, Japanese or Ukrainian. Five words a day, with spaced repetition that brings each word back before you forget it.'
  },
  'mots-du-jour': {
    title: 'Mots du jour',
    desc: 'Five French words a day, with spaced repetition that brings each word back just before you would have forgotten it.'
  },
  'spanish': {
    title: 'Palabras del día',
    desc: 'Five Spanish words a day, with spaced repetition that brings each word back just before you would have forgotten it.'
  },
  'portuguese': {
    title: 'Palavras do dia',
    desc: 'Five Portuguese words a day, with spaced repetition that brings each word back just before you would have forgotten it.'
  },
  'japanese': {
    title: '今日の単語 — Japanese word of the day',
    desc: 'Five Japanese words a day, with spaced repetition that brings each word back just before you would have forgotten it.'
  },
  'ukrainian': {
    title: 'Слова дня — Ukrainian word of the day',
    desc: 'Five Ukrainian words a day, with spaced repetition that brings each word back just before you would have forgotten it.'
  },
  'coffee': {
    title: 'Coffee notes',
    desc: 'Tasting notes on 52 coffee beans from six Oslo roasters, with a map of where to find them and what each one tasted like.'
  },
  'snake': {
    title: 'Snake',
    desc: 'Snake, in a small canvas. Arrow keys on a desktop, swipe on a phone. Your best score is kept on your own device.'
  }
};

// Anything we inject is fenced by these markers so a re-run replaces the block
// instead of stacking a second copy of every tag.
const OPEN = '  <!-- meta:begin (generated by tools/add-head-meta.js) -->';
const CLOSE = '  <!-- meta:end -->';

function block(slug, { title, desc }) {
  const url = slug === 'index' ? `${SITE}/` : `${SITE}/${slug}.html`;
  return [
    OPEN,
    `  <meta name="description" content="${desc}">`,
    `  <link rel="canonical" href="${url}">`,
    `  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">`,
    `  <meta property="og:type" content="website">`,
    `  <meta property="og:url" content="${url}">`,
    `  <meta property="og:title" content="${title}">`,
    `  <meta property="og:description" content="${desc}">`,
    `  <meta property="og:image" content="${SITE}/assets/og/${slug}.png">`,
    `  <meta property="og:image:width" content="1200">`,
    `  <meta property="og:image:height" content="630">`,
    `  <meta property="og:site_name" content="Katja Norstad">`,
    `  <meta name="twitter:card" content="summary_large_image">`,
    `  <meta name="twitter:title" content="${title}">`,
    `  <meta name="twitter:description" content="${desc}">`,
    `  <meta name="twitter:image" content="${SITE}/assets/og/${slug}.png">`,
    CLOSE
  ].join('\n');
}

let changed = 0;
for (const [slug, meta] of Object.entries(PAGES)) {
  const file = path.join(ROOT, `${slug}.html`);
  const before = fs.readFileSync(file, 'utf8');
  let src = before;

  // 1. Drop any previously generated block. The leading [ \t]* and trailing
  //    \n? matter: without them the block's own indentation and newline
  //    survived every removal, so each run left one more whitespace-only line
  //    behind and the file never converged.
  src = src.replace(/[ \t]*<!-- meta:begin \(generated by tools\/add-head-meta\.js\) -->[\s\S]*?<!-- meta:end -->\n?/g, '');

  // 2. Remove any hand-written favicon. Ten of the twelve pages carried their
  //    own ~400-byte base64 copy of the same icon; the block below replaces
  //    them all with one cacheable file. Leaving them in place would mean two
  //    competing rel="icon" declarations per page.
  src = src.replace(/[ \t]*<link rel="icon"[^>]*>\n?/g, '');

  // 3. Heal whitespace-only lines left just after </title> by earlier runs of
  //    the buggy removal above, so re-running converges instead of drifting.
  src = src.replace(/(<\/title>)(?:[ \t]*\n)+/, '$1\n');

  // 4. Insert the fresh block directly after </title>.
  if (!/<\/title>/.test(src)) throw new Error(`${slug}.html has no <title>`);
  src = src.replace(/(<\/title>)/, `$1\n${block(slug, meta)}`);

  // 5. Normalise the DM Mono weights so all 12 pages share one cached URL.
  src = src.replace(/DM\+Mono:wght@300;400(?!;500)/g, CANONICAL_MONO);

  // 6. The stylesheet comes from googleapis, the font files from gstatic.
  //    crossorigin is required: fonts are fetched in CORS mode, and a
  //    preconnect without it opens a connection that cannot be reused.
  if (src.includes('fonts.googleapis.com') && !src.includes('fonts.gstatic.com')) {
    src = src.replace(
      /([ \t]*<link rel="preconnect" href="https:\/\/fonts\.googleapis\.com"[^>]*>)/,
      `$1\n  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>`
    );
  }

  // 7. Leaflet blocks the parser at the top of coffee.html. defer lets the
  //    page render first.
  //
  //    This is only safe because coffee.html's inline map code was moved into
  //    a DOMContentLoaded listener at the same time. Inline scripts run at
  //    parse time, which is BEFORE any deferred script executes, so adding
  //    defer on its own left `L` undefined and killed the map. Enforced by
  //    tests/inline-scripts.test.js.
  src = src.replace(
    /(<script src="https:\/\/unpkg\.com\/leaflet@[^"]+")(\s*>)/,
    '$1 defer$2'
  );

  // 8. Link the shared stylesheet immediately before the page's own <style>.
  //    Order matters: site.css first means a page rule of equal specificity
  //    still wins, so the inline blocks keep overriding the shared ones.
  //
  //    The removal runs first and unconditionally, so a re-run replaces the
  //    link rather than stacking a second copy — same reason the meta block
  //    is fenced by markers.
  src = src.replace(/[ \t]*<link rel="stylesheet" href="assets\/css\/site\.css">\n?/g, '');
  src = src.replace(/([ \t]*)<style>/, '$1<link rel="stylesheet" href="assets/css/site.css">\n$1<style>');

  if (src !== before) {
    fs.writeFileSync(file, src);
    changed++;
    console.log(`  updated ${slug}.html`);
  } else {
    console.log(`  unchanged ${slug}.html`);
  }
}
console.log(`\n${changed} of ${Object.keys(PAGES).length} pages updated.`);
